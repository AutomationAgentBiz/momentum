/* Momentum's Claude backend. The Anthropic key lives here as a Netlify
   environment variable (ANTHROPIC_API_KEY) and never reaches a browser or the
   sync store. Only a device that knows a real sync code can use it, and each
   code gets a daily cap so a leaked code can't run up a bill. */
var CORS = {
  "access-control-allow-origin": "*",
  "access-control-allow-methods": "GET,POST,OPTIONS",
  "access-control-allow-headers": "content-type,x-momentum-room",
  "cache-control": "no-store"
};
var json = (body, status = 200) => new Response(JSON.stringify(body), { status, headers: { ...CORS, "content-type": "application/json" } });
var MODELS = ["claude-sonnet-5", "claude-haiku-4-5", "claude-opus-5"];
var DAILY_CAP = +(process.env.MOMENTUM_AI_DAILY_CAP || 400);
var ai_source_default = async (req) => {
  if (req.method === "OPTIONS") return new Response(null, { status: 204, headers: CORS });
  const key = process.env.ANTHROPIC_API_KEY || "";
  if (req.method === "GET") return json({ ready: !!key });
  if (req.method !== "POST") return json({ error: "Use GET or POST" }, 405);
  if (!key) return json({ error: "no_key", message: "ANTHROPIC_API_KEY isn't set on this Netlify site yet." }, 503);
  const room = (req.headers.get("x-momentum-room") || "").toUpperCase().replace(/[^A-Z0-9]/g, "");
  if (room.length < 6) return json({ error: "no_room", message: "Turn on sync in Settings so this device has a code." }, 401);
  let sync, usage;
  try {
    sync = getStore({ name: "momentum-sync", consistency: "strong" });
    usage = getStore({ name: "momentum-ai-usage", consistency: "strong" });
  } catch (e) {
    return json({ error: "storage", message: e.message }, 500);
  }
  let known = null;
  try { known = await sync.getMetadata(room); } catch (e) {}
  if (!known) return json({ error: "unknown_room", message: "That sync code isn't in use yet. Send your data up once from Settings." }, 401);
  const day = new Date().toISOString().slice(0, 10);
  const ukey = room + ":" + day;
  let used = 0;
  try { used = +((await usage.get(ukey, { type: "json" })) || {}).n || 0; } catch (e) {}
  if (used >= DAILY_CAP) return json({ error: "cap", message: "Today's AI limit is used up. It resets at midnight UTC." }, 429);
  let body;
  try { body = await req.json(); } catch (e) { return json({ error: "Body wasn't JSON" }, 400); }
  const model = MODELS.includes(body.model) ? body.model : "claude-sonnet-5";
  const messages = Array.isArray(body.messages) ? body.messages.slice(-24)
    : [{ role: "user", content: String(body.user || "").slice(0, 20000) }];
  const payload = {
    model,
    max_tokens: Math.min(+body.max_tokens || 900, 2000),
    system: String(body.system || "").slice(0, 60000),
    messages
  };
  try { await usage.setJSON(ukey, { n: used + 1 }); } catch (e) {}
  let r;
  try {
    r = await fetch("https://api.anthropic.com/v1/messages", {
      method: "POST",
      headers: { "content-type": "application/json", "x-api-key": key, "anthropic-version": "2023-06-01" },
      body: JSON.stringify(payload)
    });
  } catch (e) {
    return json({ error: "unreachable", message: "Couldn't reach Anthropic: " + e.message }, 502);
  }
  const txt = await r.text();
  if (!r.ok) return json({ error: "anthropic", status: r.status, message: txt.slice(0, 300) }, r.status);
  let j = {};
  try { j = JSON.parse(txt); } catch (e) {}
  const text = (j.content || []).map((c) => c.text || "").join("");
  return json({ text, model, used: used + 1, cap: DAILY_CAP });
};
